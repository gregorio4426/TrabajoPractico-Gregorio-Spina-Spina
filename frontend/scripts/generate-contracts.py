"""Generate frontend-only TS definitions from the unchanged backend OpenAPI export."""
import json,pathlib
root=pathlib.Path(__file__).resolve().parents[1]
spec=json.loads((root.parent/'simulacro_nombreAlumno/docs/openapi.json').read_text())
def ts(s):
 if '$ref' in s:return s['$ref'].split('/')[-1]
 if 'enum' in s:return ' | '.join(json.dumps(x) for x in s['enum'])
 if s.get('type')=='array':return f'Array<{ts(s["items"])}>'
 return {'string':'string','number':'number','integer':'number','boolean':'boolean','object':'Record<string, unknown>'}.get(s.get('type'),'unknown')
out=['// Generated by scripts/generate-contracts.py from backend docs/openapi.json.\n// Optional DTO fields may be null at runtime; the UI preserves unknown values.\n']
for name,schema in spec['components']['schemas'].items():
 out.append(f'export interface {name} {{')
 for name2,s in schema.get('properties',{}).items():
  required=name2 in schema.get('required',[])
  suffix='' if required else '?'
  null=' | null' if s.get('nullable') or not required else ''
  out.append(f'  {name2}{suffix}: {ts(s)}{null};')
 out.append('}\n')
(root/'src/app/admin/contracts.ts').write_text('\n'.join(out))
